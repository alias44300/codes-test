const fs=require('fs');const vm=require('vm');const assert=require('assert');
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
const match=html.match(/const DATA=(\{.*?\});\nconst ENTRIES=/s);
assert(match,'Catalog data not found');const data=JSON.parse(match[1]);
const countries=data.entries.filter(x=>x.type==='country');
const brands=data.entries.filter(x=>x.type==='brand');
assert.strictEqual(countries.length,45);assert.strictEqual(brands.length,362);
const codes=new Set(countries.map(x=>x.country));
assert.strictEqual(codes.size,45);
assert(brands.every(x=>codes.has(x.country||'ORIGINE À PRÉCISER')),'All brands must belong to a visible country');
assert.strictEqual(brands.filter(x=>x.country===null).length,21);
assert.strictEqual(brands.filter(x=>x.country==='Mexique').length,49);
assert.strictEqual(brands.filter(x=>x.country==='Canada').length,6);
assert(countries.some(x=>x.country==='ORIGINE À PRÉCISER'));
assert(countries.some(x=>x.country==='Autriche'));
for(const x of ['Arménie','Finlande','Suisse','Indonésie','Ouzbékistan','Irlande'])assert(countries.some(c=>c.country===x),'Missing verified country '+x);
const orig=brands.filter(x=>x.id.startsWith('p')&&Number(x.id.slice(1))>=289);
const aud=orig.filter(x=>x.originAuditDate==='2026-11-06');
assert(aud.length>=83,'Audit coverage must include all initial 83 unclassified brands');
assert.strictEqual(aud.filter(x=>x.country&&x.originStatus==='probable').length,18);
assert.strictEqual(aud.filter(x=>x.country&&x.originSource).length,62);
assert.strictEqual(aud.filter(x=>!x.country&&x.originStatus==='non confirmé').length,21);
assert(html.includes('ORIGIN_AUDIT'),'Audit metadata missing');
assert.strictEqual(brands.find(x=>x.id==='p144')?.title,'TIGRAO');
assert.strictEqual(brands.find(x=>x.id==='p137')?.title,'adidas SHORI (ADISHORI)');
assert.strictEqual(brands.filter(x=>x.country==='Japon').length,9);
assert.strictEqual(brands.filter(x=>/TIGRAO|Chiguron/i.test(x.title)).length,1);
assert.strictEqual(brands.filter(x=>/SHORI|ADISHORI/i.test(x.title)).length,1);
assert.strictEqual(brands.find(x=>x.id==='p144')?.originSource,'https://ameblo.jp/tigrao/entry-12358444319.html');

for (const id of ['p46','p132','p295','p300','p354']) assert(!brands.some(x=>x.id===id), 'duplicate brand '+id);
for (const [id,country] of Object.entries({p110:'Royaume-Uni',p251:'États-Unis',p296:'Royaume-Uni',p299:'Royaume-Uni',p301:'États-Unis',p308:'Espagne',p339:'Canada',p347:'Australie',p370:'Autriche',p378:'Royaume-Uni',p402:'France',p327:'Canada',p332:'Pays-Bas',p364:'Mexique',p408:'Pays-Bas',p391:'États-Unis'})) assert.strictEqual(brands.find(x=>x.id===id)?.country,country);
assert(html.includes('LEGACY_MERGES')&&html.includes('migrateLegacyRecords'),'preserve legacy images and biographies');
assert(html.includes('Object.keys(LEGACY_MERGES)'),'export legacy photos');
for(const id of ['catalogueBrowser','catalogueCountries','catalogueBrands','countryButtons','brandButtons','backCountries','openCatalogue','globalBrandSearch','countryBrandSearch','letterNav'])assert(html.includes('id="'+id+'"'),'Missing UI '+id);
for(const fn of ['catCountries','catOpenCountry','catRenderBrands','catOpenEditor','catShowCountries','catGlobalFilter','catAdjacent','catCountryOf'])assert(html.includes('function '+fn+'('),'Missing navigation '+fn);
assert(html.includes('catShowCountries();'),'Start should show countries');
assert(html.includes('catAdjacent(-1)')&&html.includes('catAdjacent(1)'));
const script=html.match(/<script>([\s\S]*?)<\/script>/);assert(script);new vm.Script(script[1]);
const sorter=new Intl.Collator('fr',{sensitivity:'base',numeric:true});
const sorted=brands.filter(x=>x.country==='Mexique').map(x=>x.title).sort(sorter.compare);
assert(sorted.indexOf('Campeón / Deportes Campeón')<sorted.indexOf('DC Boxing Mexico'));
assert(sorted.indexOf('DC Boxing Mexico')<sorted.indexOf('Guzmán Boxing'));
console.log('PASS: 45 countries, 362 brands, 21 unknown, Mexico 49, navigation JS valid');
